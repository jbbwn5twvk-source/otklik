# Короткий ответ человеку, который сам написал «нужен сайт / бот» в чате или канале
LEAD = {
    "site": "Здравствуйте! Увидела ваше сообщение про сайт. Делаю лендинги на Тильде и на коде, "
            "вот пример: {sites}\nРасскажите, чем занимаетесь, прикину сроки и цену.",
    "bot": "Здравствуйте! Увидела, что вам нужен бот. Пишу Telegram-ботов и парсеры на Python. "
           "Расскажите, что бот должен делать, и я назову срок и цену.",
}


def kind(o):
    text = f"{o.get('title', '')} {o.get('text', '')[:300]}"
    for k, rx in KINDS:
        if re.search(rx, text, re.I):
            return k
    return None


def draft(o, lead=False):
    k = kind(o)
    if not k:
        return ""
    tpl = (LEAD.get(k) if lead else None) or DRAFTS[k]
    later = "пришлю в ответ"
    return tpl.format(pres=PORTFOLIO.get("pres") or later, sites=PORTFOLIO.get("sites") or later)
